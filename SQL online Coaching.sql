CREATE DATABASE IF NOT EXISTS online_learning
    DEFAULT CHARACTER SET utf8mb4;
USE online_learning;


CREATE TABLE students (
    student_id     INT           NOT NULL,
    full_name      VARCHAR(100)  NOT NULL,
    email          VARCHAR(150)  NOT NULL,
    country        VARCHAR(50)   NOT NULL,
    signup_date    DATE          NOT NULL,
    PRIMARY KEY (student_id),
    UNIQUE KEY uq_students_email (email)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE courses (
    course_id      INT           NOT NULL,
    course_title   VARCHAR(100)  NOT NULL,
    category       VARCHAR(50)   NOT NULL,
    level          VARCHAR(20)   NOT NULL,
    instructor     VARCHAR(100)  NOT NULL,
    price_usd      DECIMAL(8,2)  NOT NULL,
    duration_hours INT           NOT NULL,
    PRIMARY KEY (course_id),
    CONSTRAINT chk_courses_level CHECK (level IN ('Beginner','Intermediate','Advanced')),
    CONSTRAINT chk_courses_price CHECK (price_usd >= 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE enrollments (
    enrollment_id   INT           NOT NULL,
    student_id      INT           NOT NULL,
    course_id       INT           NOT NULL,
    enrollment_date DATE          NOT NULL,
    status          VARCHAR(20)   NOT NULL,
    progress_pct    DECIMAL(5,1)  NOT NULL,
    completion_date DATE          NULL,
    PRIMARY KEY (enrollment_id),
    UNIQUE KEY uq_enroll_student_course (student_id, course_id),
    KEY idx_enroll_course (course_id),
    CONSTRAINT fk_enroll_student FOREIGN KEY (student_id) REFERENCES students (student_id),
    CONSTRAINT fk_enroll_course  FOREIGN KEY (course_id)  REFERENCES courses (course_id),
    CONSTRAINT chk_enroll_status   CHECK (status IN ('Completed','In Progress','Dropped')),
    CONSTRAINT chk_enroll_progress CHECK (progress_pct BETWEEN 0 AND 100)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE assessments (
    assessment_id   INT           NOT NULL,
    enrollment_id   INT           NOT NULL,
    assessment_type VARCHAR(20)   NOT NULL,
    score           DECIMAL(5,1)  NOT NULL,
    max_score       DECIMAL(5,1)  NOT NULL,
    attempt_date    DATE          NOT NULL,
    PRIMARY KEY (assessment_id),
    KEY idx_assess_enroll (enrollment_id),
    CONSTRAINT fk_assess_enroll FOREIGN KEY (enrollment_id) REFERENCES enrollments (enrollment_id),
    CONSTRAINT chk_assess_type CHECK (assessment_type IN ('Quiz','Assignment','Final Exam'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;


