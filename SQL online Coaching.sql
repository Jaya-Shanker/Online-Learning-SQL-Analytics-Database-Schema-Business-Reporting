-- ---------------------------------------------------------------------
-- 3.0  Reusable view: course scorecard (enrollment · completion · performance)
-- ---------------------------------------------------------------------
CREATE VIEW course_scorecard AS
SELECT
    c.course_id,
    c.course_title,
    c.category,
    c.level,
    COUNT(e.enrollment_id)                                              AS total_enrollments,
    SUM(CASE WHEN e.status = 'Completed'   THEN 1 ELSE 0 END)           AS completed,
    SUM(CASE WHEN e.status = 'In Progress' THEN 1 ELSE 0 END)           AS in_progress,
    SUM(CASE WHEN e.status = 'Dropped'     THEN 1 ELSE 0 END)           AS dropped,
    ROUND(100.0 * SUM(CASE WHEN e.status = 'Completed' THEN 1 ELSE 0 END)
          / COUNT(e.enrollment_id), 1)                                  AS completion_rate_pct,
    ROUND(100.0 * SUM(CASE WHEN e.status = 'Dropped' THEN 1 ELSE 0 END)
          / COUNT(e.enrollment_id), 1)                                  AS dropout_rate_pct,
    ROUND(AVG(e.progress_pct), 1)                                       AS avg_progress_pct,
    ROUND(SUM(c.price_usd), 0)                                          AS gross_revenue_usd
FROM courses c
LEFT JOIN enrollments e ON e.course_id = c.course_id
GROUP BY c.course_id, c.course_title, c.category, c.level;

-- ---------------------------------------------------------------------
-- 3.1  Executive KPI summary
-- ---------------------------------------------------------------------
SELECT
    (SELECT COUNT(*) FROM students)                                          AS total_students,
    (SELECT COUNT(*) FROM courses)                                           AS total_courses,
    COUNT(*)                                                                 AS total_enrollments,
    ROUND(100.0 * SUM(status = 'Completed')   / COUNT(*), 1)                 AS completion_rate_pct,
    ROUND(100.0 * SUM(status = 'Dropped')     / COUNT(*), 1)                 AS dropout_rate_pct,
    ROUND(100.0 * SUM(status = 'In Progress') / COUNT(*), 1)                 AS in_progress_pct,
    ROUND(AVG(progress_pct), 1)                                              AS avg_progress_pct,
    (SELECT ROUND(100.0 * SUM(score) / SUM(max_score), 1) FROM assessments)  AS overall_avg_score_pct
FROM enrollments;

-- ---------------------------------------------------------------------
-- 3.2  Course scorecard: enrollments, completion and average score
-- ---------------------------------------------------------------------
SELECT
    s.course_title,
    s.level,
    s.total_enrollments,
    s.completed,
    s.completion_rate_pct,
    s.dropout_rate_pct,
    ROUND(100.0 * SUM(a.score) / SUM(a.max_score), 1)  AS avg_score_pct
FROM course_scorecard s
LEFT JOIN enrollments e ON e.course_id     = s.course_id
LEFT JOIN assessments a ON a.enrollment_id = e.enrollment_id
GROUP BY s.course_id, s.course_title, s.level, s.total_enrollments,
         s.completed, s.completion_rate_pct, s.dropout_rate_pct
ORDER BY s.total_enrollments DESC;

-- ---------------------------------------------------------------------
-- 3.3  Category performance
-- ---------------------------------------------------------------------
SELECT
    c.category,
    COUNT(DISTINCT c.course_id)                                                   AS courses,
    COUNT(e.enrollment_id)                                                        AS enrollments,
    ROUND(100.0 * SUM(CASE WHEN e.status = 'Completed' THEN 1 ELSE 0 END)
          / COUNT(e.enrollment_id), 1)                                            AS completion_rate_pct,
    ROUND(SUM(c.price_usd), 0)                                                    AS gross_revenue_usd
FROM courses c
JOIN enrollments e ON e.course_id = c.course_id
GROUP BY c.category
ORDER BY enrollments DESC;

-- ---------------------------------------------------------------------
-- 3.4  Monthly enrollment trend with running total
-- ---------------------------------------------------------------------
WITH monthly AS (
    SELECT DATE_FORMAT(enrollment_date, '%Y-%m') AS month,
           COUNT(*)                              AS new_enrollments
    FROM enrollments
    GROUP BY DATE_FORMAT(enrollment_date, '%Y-%m')
)
SELECT
    month,
    new_enrollments,
    SUM(new_enrollments) OVER (ORDER BY month)                               AS cumulative_enrollments,
    ROUND(100.0 * (new_enrollments - LAG(new_enrollments) OVER (ORDER BY month))
          / LAG(new_enrollments) OVER (ORDER BY month), 1)                   AS mom_growth_pct
FROM monthly
ORDER BY month;

-- ---------------------------------------------------------------------
-- 3.5  Average time to complete vs. course length
-- ---------------------------------------------------------------------
SELECT
    c.course_title,
    c.duration_hours,
    COUNT(*)                                                             AS completers,
    ROUND(AVG(DATEDIFF(e.completion_date, e.enrollment_date)), 1)        AS avg_days_to_complete
FROM enrollments e
JOIN courses c ON c.course_id = e.course_id
WHERE e.status = 'Completed'
GROUP BY c.course_id, c.course_title, c.duration_hours
ORDER BY avg_days_to_complete;

-- ---------------------------------------------------------------------
-- 3.6  Learner leaderboard: top 10 by average score (min. 3 assessments)
--      Note: RANK is a reserved word in MySQL 8, so the alias is quoted.
-- ---------------------------------------------------------------------
WITH learner_scores AS (
    SELECT
        st.student_id,
        st.full_name,
        st.country,
        COUNT(a.assessment_id)                                AS assessments_taken,
        COUNT(DISTINCT e.course_id)                           AS courses_taken,
        ROUND(100.0 * SUM(a.score) / SUM(a.max_score), 1)     AS avg_score_pct
    FROM students st
    JOIN enrollments e ON e.student_id    = st.student_id
    JOIN assessments a ON a.enrollment_id = e.enrollment_id
    GROUP BY st.student_id, st.full_name, st.country
    HAVING COUNT(a.assessment_id) >= 3
)
SELECT
    RANK() OVER (ORDER BY avg_score_pct DESC) AS `rank`,
    full_name, country, courses_taken, assessments_taken, avg_score_pct
FROM learner_scores
ORDER BY `rank`
LIMIT 10;

-- ---------------------------------------------------------------------
-- 3.7  Best-performing course per category (window function)
-- ---------------------------------------------------------------------
WITH ranked AS (
    SELECT
        category, course_title, completion_rate_pct, total_enrollments,
        ROW_NUMBER() OVER (PARTITION BY category ORDER BY completion_rate_pct DESC) AS rn
    FROM course_scorecard
)
SELECT category, course_title, completion_rate_pct, total_enrollments
FROM ranked
WHERE rn = 1
ORDER BY completion_rate_pct DESC;

-- ---------------------------------------------------------------------
-- 3.8  Final-exam score distribution
-- ---------------------------------------------------------------------
SELECT
    CASE
        WHEN 100.0 * score / max_score >= 90 THEN 'A  (90-100)'
        WHEN 100.0 * score / max_score >= 80 THEN 'B  (80-89)'
        WHEN 100.0 * score / max_score >= 70 THEN 'C  (70-79)'
        WHEN 100.0 * score / max_score >= 60 THEN 'D  (60-69)'
        ELSE                                        'F  (<60)'
    END                                                                AS grade_band,
    COUNT(*)                                                           AS students,
    ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 1)                 AS pct_of_total
FROM assessments
WHERE assessment_type = 'Final Exam'
GROUP BY grade_band
ORDER BY grade_band;

-- ---------------------------------------------------------------------
-- 3.9  Completion rate by student country (min. 10 enrollments)
-- ---------------------------------------------------------------------
SELECT
    st.country,
    COUNT(*)                                                                AS enrollments,
    ROUND(100.0 * SUM(CASE WHEN e.status = 'Completed' THEN 1 ELSE 0 END)
          / COUNT(*), 1)                                                    AS completion_rate_pct
FROM enrollments e
JOIN students st ON st.student_id = e.student_id
GROUP BY st.country
HAVING COUNT(*) >= 10
ORDER BY completion_rate_pct DESC;

-- ---------------------------------------------------------------------
-- 3.10  Stalled learners: in progress, under 90% done, no activity for 30+ days
--       (as-of date fixed at 2026-09-15; use CURDATE() for live data)
-- ---------------------------------------------------------------------
SELECT
    st.full_name,
    st.email,
    c.course_title,
    e.enrollment_date,
    e.progress_pct,
    MAX(a.attempt_date)                                                         AS last_assessment,
    DATEDIFF('2026-09-15', COALESCE(MAX(a.attempt_date), e.enrollment_date))    AS days_inactive
FROM enrollments e
JOIN students st ON st.student_id = e.student_id
JOIN courses  c  ON c.course_id   = e.course_id
LEFT JOIN assessments a ON a.enrollment_id = e.enrollment_id
WHERE e.status = 'In Progress'
  AND e.progress_pct < 90
GROUP BY e.enrollment_id, st.full_name, st.email, c.course_title,
         e.enrollment_date, e.progress_pct
HAVING days_inactive >= 30
ORDER BY days_inactive DESC;
